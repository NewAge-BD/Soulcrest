using Soulcrest.Ocr;
using Xunit;

namespace Soulcrest.Ocr.Tests;

public sealed class GameLanguageCategoryTests
{
    [Theory]
    [InlineData("Versiegelter Dungeon", "de")]
    [InlineData("Versiegelte Dungeons", "de")]
    [InlineData("Versiegelter Dunge...", "de")]
    [InlineData(" VERSIEGELTER DUNGE… ", "de")]
    [InlineData("Versiegelter Dunge.«", "de")]
    [InlineData("Versiegelter Dunge.„", "de")]
    [InlineData("Garnison", "de")]
    [InlineData("Garnisonen", "de")]
    [InlineData("Sealed Dungeon", "en")]
    [InlineData("Sealed Dungeons", "en")]
    [InlineData("Stronghold", "en")]
    [InlineData("Strongholds", "en")]
    [InlineData("Versiegelter Dunge... 31 %", "de")]
    [InlineData("Versiegelter Dunge.« 31 %", "de")]
    [InlineData("Versiegelter Dunge.„ 31 %", "de")]
    [InlineData("Versiegelter Dungeon 100 %", "de")]
    [InlineData("Garnisonen 0 %", "de")]
    [InlineData("Sealed Dungeons 31 %", "en")]
    [InlineData("Strongholds 100 %", "en")]
    [InlineData("(O) Versiegelter Dunge...", "de")]
    [InlineData("(O) Sealed Dungeon", "en")]
    [InlineData("(O) Versiegelter Dunge... 31 %", "de")]
    [InlineData("(O) Versiegelter Dunge.« 31 %", "de")]
    [InlineData("(O) Versiegelter Dunge.„ 31 %", "de")]
    [InlineData("(O) Garnisonen 100 %", "de")]
    [InlineData("(O) Sealed Dungeon 31 %", "en")]
    [InlineData("(O) Stronghold 100 %", "en")]
    public void AWholeKnownCategoryHeadingSelectsItsClientLanguage(string text, string language) =>
        Assert.Equal(language, GameLanguageDetector.Detect([text]));

    [Theory]
    [InlineData("Versiegelter Dunge...", "Sealed Dungeon")]
    [InlineData("Garnison", "Stronghold")]
    [InlineData("Versiegelter Dungeon", "Pet Insight")]
    [InlineData("Stronghold", "Bindung abgeschlossen")]
    [InlineData("Sealed Dungeon", "Sammlungsfortschritt 174/200")]
    [InlineData("(O) Versiegelter Dunge... 31 %", "Sealed Dungeon 99 %")]
    [InlineData("Garnisonen 100 %", "(O) Stronghold 100 %")]
    [InlineData("(O) Versiegelter Dunge... 31 %", "Pet Insight")]
    [InlineData("(O) Stronghold 31 %", "Bindung abgeschlossen")]
    [InlineData("(O) Sealed Dungeon 31 %", "Sammlungsfortschritt 174/200")]
    [InlineData("Versiegelter Dunge.«", "Sealed Dungeon")]
    [InlineData("(O) Versiegelter Dunge.„ 31 %", "Pet Insight")]
    public void ConflictingCategoryAndExistingScanCaptionsRemainUncertain(string first, string second) =>
        Assert.Null(GameLanguageDetector.Detect([first, second]));

    [Theory]
    [InlineData("Kibelisk")]
    [InlineData("100 %")]
    [InlineData("Karte: Altgard")]
    [InlineData("Versiegelter Dunge")]
    [InlineData("Versiegelter D...")]
    [InlineData("Sealed Dunge...")]
    [InlineData("Garnis...")]
    [InlineData("Map: Sealed Dungeon")]
    [InlineData("Other Versiegelter Dunge...")]
    [InlineData("Map: Sealed Dungeon 31 %")]
    [InlineData("Karte: Versiegelter Dunge... 31 %")]
    [InlineData("Quest: Sealed Dungeon 31 %")]
    [InlineData("Quest: Versiegelter Dunge... 31 %")]
    [InlineData("(0) Sealed Dungeon 31 %")]
    [InlineData("Sealed Dungeon %")]
    [InlineData("Sealed Dungeon 101 %")]
    [InlineData("Sealed Dungeon -1 %")]
    [InlineData("Sealed Dungeon 31.5 %")]
    [InlineData("Sealed Dungeon 31 %%")]
    [InlineData("(O) Versiegelter Dunge... 31 % Unentdeckt")]
    [InlineData("Sealed Dungeon Stronghold 31 %")]
    [InlineData("Versiegelter Dunge... Sealed Dungeon 31 %")]
    [InlineData("Versiegelter Dunge.‹")]
    [InlineData("Versiegelter Dunge.»")]
    [InlineData("Versiegelter Dunge.“")]
    [InlineData("Versiegelter Dunge«")]
    [InlineData("Sealed Dunge.„ 31 %")]
    [InlineData("Sealed Dungeon.« 31 %")]
    [InlineData("Versiegelter Dungeon.„ 31 %")]
    [InlineData("Stronghold.«")]
    [InlineData("Garnison.„")]
    [InlineData("Versiegelter Dunge.« 31 % Unentdeckt")]
    public void PartialOrUnrelatedTextDoesNotSelectALanguage(string text) =>
        Assert.Null(GameLanguageDetector.Detect([text]));
}
